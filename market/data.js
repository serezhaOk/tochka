// Детерминированный генератор, чтобы демо-лента была одинаковой при каждой загрузке.
function seededRandom(seed) {
  let s = seed;
  return () => (s = (s * 16807) % 2147483647) / 2147483647;
}

function buildListings() {
  const rnd = seededRandom(42);
  const pick = (arr) => arr[Math.floor(rnd() * arr.length)];
  const list = [];
  let id = 1;
  const now = Date.now();
  for (const cat of CATEGORIES) {
    for (const [title, price, emoji, sub, unit] of TEMPLATES[cat.id]) {
      const copies = 1 + Math.floor(rnd() * 2);
      for (let i = 0; i < copies; i++) {
        const jitter = price === 0 ? 0 : Math.round((price * (0.85 + rnd() * 0.3)) / 100) * 100;
        list.push({
          id: String(id++),
          title,
          price: jitter,
          unit: unit || '',
          category: cat.id,
          sub,
          emoji,
          city: pick(CITIES),
          district: pick(DISTRICTS),
          createdAt: now - Math.floor(rnd() * 14 * 24 * 3600 * 1000),
          views: 20 + Math.floor(rnd() * 1500),
          seller: pick(SELLERS),
          description: `${pick(DESCRIPTIONS)} ${pick(DESCRIPTIONS)}`,
          delivery: rnd() > 0.55,
          photos: 1 + Math.floor(rnd() * 4),
        });
      }
    }
  }
  return list;
}

